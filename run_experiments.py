#!/usr/bin/env python3
"""Run ideal and FakeBrisbane-derived noisy AER simulations for the QCT circuits."""
from __future__ import annotations

import argparse
import csv
import json
import math
import platform
from collections import Counter
from pathlib import Path

import numpy as np
import qiskit
import qiskit_aer
import qiskit_ibm_runtime
from qiskit import QuantumCircuit, transpile
from qiskit_aer import AerSimulator
from qiskit_ibm_runtime.fake_provider import FakeBrisbane

from qct_circuits import four_tap_fir_circuit, reduced_full_qct_circuit


def probabilities(counts: Counter, shots: int) -> dict[str, float]:
    return {k.replace(" ", ""): v / shots for k, v in counts.items()}


def hellinger_fidelity(p: dict[str, float], q: dict[str, float]) -> float:
    keys = set(p) | set(q)
    coefficient = sum(math.sqrt(p.get(k, 0.0) * q.get(k, 0.0)) for k in keys)
    return float(coefficient * coefficient)


def total_variation_distance(p: dict[str, float], q: dict[str, float]) -> float:
    keys = set(p) | set(q)
    return float(0.5 * sum(abs(p.get(k, 0.0) - q.get(k, 0.0)) for k in keys))


def condition_fir_on_selector_zero(prob: dict[str, float]) -> tuple[float, dict[str, float]]:
    # Qiskit count strings are c5...c0. Selector is c1,c0 = rightmost two bits.
    selected = {k[:-2]: v for k, v in prob.items() if k.endswith("00")}
    success = float(sum(selected.values()))
    if success > 0:
        selected = {k: v / success for k, v in selected.items()}
    return success, selected


def op_counts(circuit: QuantumCircuit) -> dict[str, int]:
    return {str(k): int(v) for k, v in circuit.count_ops().items()}


def run_counts(qc: QuantumCircuit, simulator: AerSimulator, shots: int, seed: int) -> tuple[Counter, QuantumCircuit]:
    tqc = transpile(qc, simulator, optimization_level=3, seed_transpiler=seed)
    result = simulator.run(tqc, shots=shots, seed_simulator=seed).result()
    return Counter(result.get_counts()), tqc


def write_markdown(summary: dict, output_file: Path) -> None:
    fir = summary["experiments"]["four_tap_fir"]
    qct = summary["experiments"]["reduced_full_qct"]
    text = f"""# Reproduced FakeBrisbane results

Generated by `run_experiments.py`.

## Environment

- Backend snapshot: `{summary['backend']}` ({summary['backend_qubits']} physical qubits)
- Shots: {summary['shots']}
- Seed: {summary['seed']}
- Qiskit: {summary['software']['qiskit']}
- Qiskit Aer: {summary['software']['qiskit_aer']}
- Qiskit IBM Runtime: {summary['software']['qiskit_ibm_runtime']}
- Python: {summary['software']['python']}

## Experiment A: four-tap FIR primitive

| Metric | Value |
|---|---:|
| Logical qubits | {fir['logical_qubits']} |
| Ideal selector-00 success probability | {fir['ideal_success_probability_selector_00']:.6f} |
| Noisy selector-00 success probability | {fir['noisy_success_probability_selector_00']:.6f} |
| Conditional Hellinger fidelity | {fir['conditional_hellinger_fidelity']:.6f} |
| Conditional TVD | {fir['conditional_total_variation_distance']:.6f} |
| FakeBrisbane transpiled depth | {fir['fake_brisbane_transpiled_depth']} |
| FakeBrisbane transpiled size | {fir['fake_brisbane_transpiled_size']} |

Native operation counts: `{json.dumps(fir['fake_brisbane_op_counts'], sort_keys=True)}`

## Experiment B: complete reduced LP-to-DFB QCT

| Metric | Value |
|---|---:|
| Logical qubits | {qct['logical_qubits']} |
| Logical transform operations | {qct['logical_transform_operations']} |
| Ideal/noisy Hellinger fidelity | {qct['ideal_vs_noisy_hellinger_fidelity']:.6f} |
| Ideal/noisy TVD | {qct['ideal_vs_noisy_total_variation_distance']:.6f} |
| FakeBrisbane transpiled depth | {qct['fake_brisbane_transpiled_depth']} |
| FakeBrisbane transpiled size | {qct['fake_brisbane_transpiled_size']} |

Native operation counts: `{json.dumps(qct['fake_brisbane_op_counts'], sort_keys=True)}`

These are noisy simulations from the FakeBrisbane calibration snapshot, not live execution on IBM Brisbane.
"""
    output_file.write_text(text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--shots", type=int, default=8192)
    parser.add_argument("--seed", type=int, default=271828)
    parser.add_argument("--output-dir", type=Path, default=Path("results"))
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    fake = FakeBrisbane()
    noisy = AerSimulator.from_backend(fake)
    noisy.set_options(method="matrix_product_state")
    ideal = AerSimulator()

    summary: dict[str, object] = {
        "shots": args.shots,
        "seed": args.seed,
        "backend": fake.name,
        "backend_qubits": fake.num_qubits,
        "software": {
            "python": platform.python_version(),
            "qiskit": qiskit.__version__,
            "qiskit_aer": qiskit_aer.__version__,
            "qiskit_ibm_runtime": qiskit_ibm_runtime.__version__,
            "numpy": np.__version__,
        },
        "experiments": {},
    }

    fir = four_tap_fir_circuit(measure=True)
    ideal_counts, ideal_t = run_counts(fir, ideal, args.shots, args.seed)
    noisy_counts, noisy_t = run_counts(fir, noisy, args.shots, args.seed)
    p_i = probabilities(ideal_counts, args.shots)
    p_n = probabilities(noisy_counts, args.shots)
    succ_i, cond_i = condition_fir_on_selector_zero(p_i)
    succ_n, cond_n = condition_fir_on_selector_zero(p_n)
    summary["experiments"]["four_tap_fir"] = {
        "logical_qubits": fir.num_qubits,
        "ideal_success_probability_selector_00": succ_i,
        "noisy_success_probability_selector_00": succ_n,
        "conditional_hellinger_fidelity": hellinger_fidelity(cond_i, cond_n),
        "conditional_total_variation_distance": total_variation_distance(cond_i, cond_n),
        "ideal_transpiled_depth": ideal_t.depth(),
        "fake_brisbane_transpiled_depth": noisy_t.depth(),
        "fake_brisbane_transpiled_size": noisy_t.size(),
        "fake_brisbane_op_counts": op_counts(noisy_t),
    }

    qct = reduced_full_qct_circuit(measure=True)
    ideal_counts, ideal_t = run_counts(qct, ideal, args.shots, args.seed)
    noisy_counts, noisy_t = run_counts(qct, noisy, args.shots, args.seed)
    p_i = probabilities(ideal_counts, args.shots)
    p_n = probabilities(noisy_counts, args.shots)
    summary["experiments"]["reduced_full_qct"] = {
        "logical_qubits": qct.num_qubits,
        "logical_transform_operations": 6,
        "ideal_vs_noisy_hellinger_fidelity": hellinger_fidelity(p_i, p_n),
        "ideal_vs_noisy_total_variation_distance": total_variation_distance(p_i, p_n),
        "ideal_transpiled_depth": ideal_t.depth(),
        "fake_brisbane_transpiled_depth": noisy_t.depth(),
        "fake_brisbane_transpiled_size": noisy_t.size(),
        "fake_brisbane_op_counts": op_counts(noisy_t),
        "ideal_counts": dict(ideal_counts),
        "noisy_counts": dict(noisy_counts),
    }

    json_path = args.output_dir / "fake_brisbane_results.json"
    json_path.write_text(json.dumps(summary, indent=2, sort_keys=True), encoding="utf-8")

    with (args.output_dir / "fake_brisbane_summary.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["experiment", "metric", "value"])
        for exp_name, exp_data in summary["experiments"].items():
            for key, value in exp_data.items():
                if isinstance(value, (str, int, float)):
                    writer.writerow([exp_name, key, value])

    write_markdown(summary, args.output_dir / "RESULTS.md")
    print(json.dumps(summary, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
